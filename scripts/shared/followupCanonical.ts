function stripQuestionWrappers(pattern: string): string {
  let normalized = pattern.trim();
  while (WRAPPER_PREFIX_RE.test(normalized)) {
    normalized = normalized.replace(WRAPPER_PREFIX_RE, '').trim();
  }
  return normalized;
}

export function canonicalizeFollowupQuestionPattern(pattern: string): string {
  const normalized = stripQuestionWrappers(pattern);
  for (const [regex, target] of FOLLOWUP_CANONICAL_ALIASES) {
    if (regex.test(normalized)) return target;
  }
  return normalized;
}
